export async function seedMasterItems() {
  console.log('Seeding EMG Master Items...');
  const createdItems: Record<string, string> = {};

  for (const it of MASTER_ITEMS) {
    const item = await prisma.inventoryItem.upsert({
      where: { sku: it.sku },
      create: {
        sku: it.sku,
        name: it.name,
        categoryCode: it.categoryCode,
        subCategory: it.subCategory,
        unit: it.unit,
        isSerialized: it.isSerialized,
        currentStock: Math.round(it.stockQuantity || 0),
        purchasePrice: it.purchasePrice,
        sellingPrice: it.sellingPrice,
        minimumStock: it.minimumStock,
      },
      update: {
        name: it.name,
        categoryCode: it.categoryCode,
        subCategory: it.subCategory,
        unit: it.unit,
        isSerialized: it.isSerialized,
      },
    });
    createdItems[it.sku] = item.id;
  }

  return createdItems;
}
