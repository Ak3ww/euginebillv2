function parseVendorAndModel(sn: string): { vendor: string; model: string; sku: string } {
  const upper = sn.toUpperCase();
  if (upper.startsWith('ZTEG')) {
    return { vendor: 'ZTE', model: 'ZTE F609 V3 Gigabit', sku: 'EMG-CPE-ONT-ZTE-F609V3' };
  }
  if (upper.startsWith('SKYW')) {
    return { vendor: 'Skyworth', model: 'GN542VF Dual Band', sku: 'EMG-CPE-ONT-SKW-542VF' };
  }
  if (upper.startsWith('RTEG')) {
    return { vendor: 'Realtek', model: 'RTL8672 / ZTE OEM GPON', sku: 'EMG-CPE-ONT-RLT-OEM' };
  }
  if (upper.startsWith('YHTC')) {
    return { vendor: 'Yuhua', model: 'YH-100G GPON', sku: 'EMG-CPE-ONT-YHT-100G' };
  }
  if (upper.startsWith('FHTT')) {
    return { vendor: 'FiberHome', model: 'HG6243C GPON', sku: 'EMG-CPE-ONT-FBH-HG6243' };
  }
  if (upper.startsWith('HWTC')) {
    return { vendor: 'Huawei', model: 'EchoLife HG8245H', sku: 'EMG-CPE-ONT-HWA-8245H' };
  }
  if (upper.startsWith('GGCI') || upper.startsWith('GGCL')) {
    return { vendor: 'Gigalink', model: 'FD511G GPON', sku: 'EMG-CPE-ONT-GGL-FD511G' };
  }
  if (upper.startsWith('AZVG')) {
    return { vendor: 'VSOL', model: 'V2801 Series', sku: 'EMG-CPE-ONT-VSL-V2801' };
  }
  if (upper.startsWith('EFTT')) {
    return { vendor: 'EFiber', model: 'OEM GPON', sku: 'EMG-CPE-ONT-EFT-OEM' };
  }
  return { vendor: 'Generic', model: 'GPON ONU', sku: 'EMG-CPE-ONT-ZTE-F609V3' };
}

async function main() {
  console.log('--- STARTING INITIAL MASTER & ONU IMPORT ---');

  // Step 1: Seed Master Items
  const skuToIdMap = await seedMasterItems();
  console.log('Master Items Seeded. SKU Count:', Object.keys(skuToIdMap).length);

  // Step 2: Parse raw customers and ONUs
  const custLines = rawCustomers.split('\n').map(s => s.trim()).filter(Boolean);
  const onuParts: string[] = [];
  rawOnus.split('\n').map(s => s.trim()).filter(Boolean).forEach(line => {
    line.split(/\s+/).filter(Boolean).forEach(p => onuParts.push(p.toUpperCase()));
  });

  console.log(`Cust lines: ${custLines.length}, ONU parts: ${onuParts.length}`);

  // Build the 1-to-1 array with user corrections
  const pairs: { customerCode: string; sn: string; isBerhenti: boolean }[] = [];

  for (let i = 0; i < custLines.length; i++) {
    const cust = custLines[i];
    let sn = onuParts[i];
    const isBerhenti = cust.toUpperCase() === 'BERHENTI';

    // User confirmed specific mappings:
    // EMG239 -> ZTEGD4A3C19B
    // EMG231 -> ZTEGD10A83F4 (Berhenti)
    // EMG304 -> ZTEGDA57BA6A
    // EMG324 -> ZTEGD777639A
    if (cust.toUpperCase() === 'EMG239') sn = 'ZTEGD4A3C19B';
    if (cust.toUpperCase() === 'EMG231') sn = 'ZTEGD10A83F4';
    if (cust.toUpperCase() === 'EMG304') sn = 'ZTEGDA57BA6A';
    if (cust.toUpperCase() === 'EMG324') sn = 'ZTEGD777639A';

    pairs.push({
      customerCode: cust,
      sn,
      isBerhenti,
    });
  }

  // Filter only ACTIVE customers (exclude BERHENTI)
  const activePairs = pairs.filter(p => !p.isBerhenti && p.customerCode.toUpperCase() !== 'BERHENTI');
  console.log(`Total Active Customer ONUs to Import: ${activePairs.length}`);

  let importedCount = 0;
  let linkedCustomerCount = 0;

  for (const pair of activePairs) {
    const { customerCode, sn } = pair;
    const { vendor, model, sku } = parseVendorAndModel(sn);
    const itemId = skuToIdMap[sku] || Object.values(skuToIdMap)[0];

    // Find customer in database if exists
    let dbCustomer = null;
    try {
      dbCustomer = await prisma.pppoeUser.findFirst({
        where: {
          OR: [
            { username: { equals: customerCode } },
            { username: { equals: customerCode.toLowerCase() } },
            { customerId: { equals: customerCode } },
            { name: { contains: customerCode } },
          ],
        },
      });
    } catch {
      // Database query error handled gracefully
    }

    // Upsert inventoryAsset
    const asset = await prisma.inventoryAsset.upsert({
      where: { serialNumber: sn },
      create: {
        itemId,
        assetType: 'MODEM',
        serialNumber: sn,
        vendor,
        model,
        condition: 'NEW',
        status: 'IN_USE',
        currentCustomerId: dbCustomer?.id || null,
        notes: `Pelanggan: ${customerCode}${dbCustomer ? ` (${dbCustomer.name})` : ''}`,
        installedAt: dbCustomer?.createdAt || new Date(),
      },
      update: {
        vendor,
        model,
        status: 'IN_USE',
        ...(dbCustomer ? { currentCustomerId: dbCustomer.id } : {}),
      },
    });

    importedCount++;

    if (dbCustomer) {
      linkedCustomerCount++;
      // Create initial device history
      await prisma.customerDeviceHistory.create({
        data: {
          customerId: dbCustomer.id,
          assetId: asset.id,
          serialNumber: sn,
          vendor,
          model,
          action: 'INSTALLED',
          reason: 'Data Awal Pelanggan',
          installedAt: dbCustomer.createdAt || new Date(),
        },
      }).catch(() => {});
    }
  }

  console.log(`\n--- IMPORT COMPLETE ---`);
  console.log(`Successfully processed ${importedCount} ONUs.`);
  console.log(`Directly linked ${linkedCustomerCount} ONUs to existing DB customers.`);
}

main()
  .catch(console.error)
  .finally(() => prisma.$disconnect());
