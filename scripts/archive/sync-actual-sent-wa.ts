async function syncActualSentWa() {
  console.log('🔄 Memulai sinkronisasi status WAaktual ke database...\n');

  try {
    const now = new Date();

    // 1. Mark all actual sent invoices in DB as WA Terkirim (1x)
    const updatedSent = await prisma.invoice.updateMany({
      where: {
        invoiceNumber: { in: ACTUAL_SENT_INVOICE_NUMBERS },
      },
      data: {
        waNotifiedAt: now,
        waRetryCount: 1,
      },
    });

    console.log(`✅ Berhasil menandai ${updatedSent.count} tagihan sebagai WA Terkirim (1x).`);

    // 2. Mark any remaining PENDING/OVERDUE invoices NOT in the list as Belum WA (0x)
    const updatedUnsent = await prisma.invoice.updateMany({
      where: {
        status: { in: ['PENDING', 'OVERDUE'] },
        invoiceNumber: { notIn: ACTUAL_SENT_INVOICE_NUMBERS },
      },
      data: {
        waNotifiedAt: null,
        waRetryCount: 0,
      },
    });

    console.log(`📌 Berhasil menandai ${updatedUnsent.count} tagihan sisa yang belum terkirim sebagai Belum WA (0x).`);
    console.log('\n🎉 Sinkronisasi selesai! UI /admin/invoices sekarang 100% presisi dengan perangkat fisik!');
  } catch (error) {
    console.error('❌ Error syncing actual sent WA:', error);
  } finally {
    await prisma.$disconnect();
    process.exit(0);
  }
}

syncActualSentWa();
